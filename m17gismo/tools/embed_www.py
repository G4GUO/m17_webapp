#!/usr/bin/env python3
"""Turn the www/ directory into www_assets.h for embedding in the binary.

Usage: embed_www.py www > www_assets.h
"""
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".wav": "audio/wav",
    ".txt": "text/plain; charset=utf-8",
}


def c_array(data: bytes) -> str:
    out = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        out.append("".join(f"0x{b:02x}," for b in chunk))
    return "\n".join(out)


def main() -> int:
    root = sys.argv[1] if len(sys.argv) > 1 else "www"
    files = []
    for dirpath, _dirnames, filenames in os.walk(root):
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = "/" + os.path.relpath(full, root).replace(os.sep, "/")
            with open(full, "rb") as fh:
                files.append((rel, full, fh.read()))

    print("// generated by tools/embed_www.py - do not edit")
    print("#ifndef WWW_ASSETS_H")
    print("#define WWW_ASSETS_H")
    print('#include "webserver.h"')
    print()
    for idx, (rel, _full, data) in enumerate(files):
        print(f"static const unsigned char asset_{idx}[] = {{")
        if data:
            print(c_array(data))
        else:
            print("0x00,")
        print("};")
    print()
    print("static const WsAsset www_assets[] = {")
    for idx, (rel, full, data) in enumerate(files):
        ext = os.path.splitext(full)[1]
        mime = MIME.get(ext, "application/octet-stream")
        print(f'    {{ "{rel}", "{mime}", asset_{idx}, sizeof(asset_{idx}) }},')
    print("    { 0, 0, 0, 0 }")
    print("};")
    print()
    print("#endif // WWW_ASSETS_H")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
